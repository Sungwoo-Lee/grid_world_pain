def check_tensor(name, jax_out, ref_out, budget, verbose=True):
    """Compare two arrays and report PASS/FAIL.

    Returns (passed: bool, max_abs_diff: float).
    """
    jax_arr = np.asarray(jax_out, dtype=np.float64)
    ref_arr = np.asarray(ref_out, dtype=np.float64)

    if jax_arr.shape != ref_arr.shape:
        print(f"  FAIL [{name}]: shape mismatch: jax={jax_arr.shape} ref={ref_arr.shape}")
        return False, float("inf")

    max_abs_diff = float(np.max(np.abs(jax_arr - ref_arr)))
    passed = max_abs_diff < budget

    status = "PASS" if passed else "FAIL"
    if verbose:
        print(f"  {status} [{name}]: max_abs_diff = {max_abs_diff:.3e}  (budget {budget:.0e})")
    return passed, max_abs_diff


