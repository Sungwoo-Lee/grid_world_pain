def test_temperature_disabled_leaves_logits_untouched():
    """With temperature off, the head must not exist and the logits must be the
    un-divided ones. Built with the same seed and the same enabled sites, the two
    models share every other parameter."""
    spec = golden.SPECS["flat"]
    obs = golden.fixed_observation(spec)

    m_off = _build("flat", _mod_cfg(temperature=False))
    m_on = _build("flat", _mod_cfg(temperature=True, clip=(0.5, 3.0)))
    assert not hasattr(m_off.modulator, "head_action")
    assert hasattr(m_on.modulator, "head_action")

    logits_off, _, _, info_off = m_off(obs, m_off.initial_state())
    logits_on, _, _, info_on = m_on(obs, m_on.initial_state())
    assert info_off.temperature is None
    assert info_on.temperature is not None
    # head_action is constructed LAST among the legacy heads, so both models share
    # every parameter that feeds the task path -> the only difference is the divide.
    np.testing.assert_allclose(np.asarray(logits_on),
                               np.asarray(logits_off) / np.asarray(info_on.temperature),
                               rtol=1e-6, atol=1e-6)


def test_rnn_activation_does_not_modulate_carry():
    """D5 — the 'activation' mechanism modulates the GRU's EMITTED output only.
    Scaling the carry state that is handed to the next timestep would re-create
    the double-gating pathology the gate-bias mechanism was invented to avoid.

    Deliberately non-identity gains: the modulator's gamma head bias is pushed to
    2.0 and its beta head bias to 1.0, so if the carry were being modulated the
    difference would be large and obvious.
    """
    spec = golden.SPECS["flat"]
    obs = golden.fixed_observation(spec)

    model = _build("flat", _mod_cfg(mechanism="activation", encoder=False,
                                    rnn=True, temperature=False))
    model.modulator.head_rnn.bias.value = jnp.full_like(model.modulator.head_rnn.bias.value, 2.0)
    model.modulator.head_rnn_add.bias.value = jnp.full_like(
        model.modulator.head_rnn_add.bias.value, 1.0)

    task_h, mod_h = model.initial_state()
    x = jnp.sign(obs) * jnp.log(jnp.abs(obs) + 1.0)
    x_proj = model.obs_encoder(x, flat_ln=getattr(model, 'mod_flat_ln', None))
    expected_carry, expected_xh = model.rnn_cell(task_h, x_proj)

    logits, value, (h_new, _), mod_info = model(obs, (task_h, mod_h))

    # The carry is untouched...
    np.testing.assert_array_equal(np.asarray(h_new), np.asarray(expected_carry))
    # ...while the emitted signal really was modulated (so the test is not vacuous).
    modulated_xh = mod_info.z_rnn * expected_xh + mod_info.z_rnn_add
    assert not np.allclose(np.asarray(modulated_xh), np.asarray(expected_xh))
    expected_logits = model.actor_fc2(model._activate(model.actor_fc1(modulated_xh)))
    np.testing.assert_allclose(np.asarray(logits), np.asarray(expected_logits),
                               rtol=1e-6, atol=1e-6)


@pytest.mark.parametrize("site", ["actor", "critic", "rnn"])
def test_new_site_changes_output_and_receives_gradient(site):
    """V5 — each new site must actually do something: perturbing its gain head
    changes the model's output, and one PPO-style update gives that head a
    non-zero gradient. A head that is constructed but never read would pass
    neither check."""
    spec = golden.SPECS["flat"]
    obs = golden.fixed_observation(spec)
    on = {"encoder": False, "rnn": False, "actor": False, "critic": False}
    on[site] = True
    model = _build("flat", _mod_cfg(mechanism="activation", temperature=False, **on))

    head = getattr(model.modulator, f"head_{site}")
    h0 = model.initial_state()
    before = model(obs, h0)
    head.bias.value = head.bias.value + 0.5
    after = model(obs, h0)

    changed = (not np.allclose(np.asarray(before[0]), np.asarray(after[0]))
               or not np.allclose(np.asarray(before[1]), np.asarray(after[1])))
    assert changed, f"site '{site}' is constructed but does not affect the output"

    def loss_fn(m):
        logits, value, _, _ = m(obs, h0)
        return jnp.sum(logits ** 2) + jnp.sum(value ** 2)

    grads = nnx.grad(loss_fn)(model)
    gpath = grads["modulator"][f"head_{site}"]["kernel"]
    gval = gpath.value if hasattr(gpath, "value") else gpath
    assert float(optax.global_norm(gval)) > 0.0, (
        f"site '{site}' head received a zero gradient"
    )


def test_disabled_site_is_really_bypassed():
    """V6 — with sites.actor off, the head must be absent AND the forward pass
    must equal the model with the actor path taken plainly."""
    spec = golden.SPECS["flat"]
    obs = golden.fixed_observation(spec)
    model = _build("flat", _mod_cfg(actor=False, mechanism="activation",
                                    rnn=False, temperature=False))
    assert not hasattr(model.modulator, "head_actor")

    logits, value, _, info = model(obs, model.initial_state())
    assert info.z_actor is None and info.z_actor_add is None
    assert info.z_critic is None and info.z_memory is None and info.z_rnn is None

    x = jnp.sign(obs) * jnp.log(jnp.abs(obs) + 1.0)
    task_h, mod_h = model.initial_state()
    mod_out, _ = model.modulator(x, mod_h)
    x_proj = model.obs_encoder.forward_with_modulation(
        x, mod_out, "FiLM", flat_ln=getattr(model, 'mod_flat_ln', None))
    _, x_h = model.rnn_cell(task_h, x_proj)
    expected = model.actor_fc2(model._activate(model.actor_fc1(x_h)))
    np.testing.assert_allclose(np.asarray(logits), np.asarray(expected),
                               rtol=1e-6, atol=1e-6)


