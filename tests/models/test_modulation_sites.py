def test_legacy_temp_clip_key_raises():
    """D9 — a config still carrying the flat `temp_clip` key must fail loudly.
    The message must ALSO tell someone re-analysing an archived run that
    RE-TRAINING, not re-evaluation, is the remedy (D16), so a future message edit
    cannot quietly strip that guidance."""
    cfg = _mod_cfg()
    cfg["temp_clip"] = [0.5, 3.0]
    with pytest.raises(ValueError) as exc:
        _build("flat", cfg)
    msg = str(exc.value)
    assert "temp_clip" in msg and "temperature" in msg
    assert "RE-TRAIN" in msg.upper()
    assert "ARCHIVED" in msg.upper()


