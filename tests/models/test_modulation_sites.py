_SITE_NAMES = ("encoder", "rnn", "actor", "critic")
_SUBSETS = [s for n in range(1, 5) for s in itertools.combinations(_SITE_NAMES, n)]


@pytest.mark.parametrize("mechanism", ["activation", "gate_bias"])
@pytest.mark.parametrize("subset", _SUBSETS, ids=["+".join(s) for s in _SUBSETS])
def test_site_toggles_build_expected_heads(subset, mechanism):
    """For every non-empty combination of sites x mechanism, exactly the expected
    modulator heads and baselines exist — no more, no fewer. A head that exists
    but is never read is dead weight receiving no gradient (the failure mode of
    the fixed LSTM/z_memory bug)."""
    on = {name: (name in subset) for name in _SITE_NAMES}
    model = _build("flat", _mod_cfg(mechanism=mechanism, temperature=False, **on))
    mod = model.modulator

    expected = set()
    if on["encoder"]:
        expected |= {"head_unimodal", "head_unimodal_add", "head_multimodal",
                     "head_multimodal_add", "z_unimodal_baseline", "z_hidden_baseline",
                     "z_unimodal_add_baseline", "z_hidden_add_baseline"}
    if on["rnn"] and mechanism == "gate_bias":
        expected |= {"head_memory", "z_mem_baseline"}
    if on["rnn"] and mechanism == "activation":
        expected |= {"head_rnn", "head_rnn_add", "z_rnn_baseline", "z_rnn_add_baseline"}
    if on["actor"]:
        expected |= {"head_actor", "head_actor_add", "z_actor_baseline", "z_actor_add_baseline"}
    if on["critic"]:
        expected |= {"head_critic", "head_critic_add", "z_critic_baseline", "z_critic_add_baseline"}
    # temperature is off in this parametrisation
    assert not hasattr(mod, "head_action")

    present = {a for a in dir(mod)
               if (a.startswith("head_") or a.endswith("_baseline"))}
    assert present == expected, f"unexpected: {present - expected}, missing: {expected - present}"


def test_plain_gru_cell_used_when_not_gate_bias():
    """D6 — the hand-built ModulatedGRUCell has a different initialisation scheme
    and gate polarity from the plain nnx.GRUCell, so using it whenever modulation
    is on imports an initialisation confound into every comparison. It must now
    be built ONLY for the gate-bias mechanism."""
    from src.models.modulated_gru_cell import ModulatedGRUCell

    m_gate = _build("flat", _mod_cfg(mechanism="gate_bias"))
    assert isinstance(m_gate.rnn_cell, ModulatedGRUCell)

    for cfg in (_mod_cfg(mechanism="activation"),
                _mod_cfg(rnn=False, encoder=True),
                _mod_cfg(rnn=False, encoder=False, actor=True),
                _mod_cfg(rnn=False, encoder=False, critic=True)):
        model = _build("flat", cfg)
        assert not isinstance(model.rnn_cell, ModulatedGRUCell)
        assert isinstance(model.rnn_cell, nnx.GRUCell)


