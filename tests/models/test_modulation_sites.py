"""Tests for the modulation-site refactor — uniform FiLM at selectable sites.

Plain-language context: the agent carries a small second network (the
"neuromodulator") that continuously re-tunes the main policy network. It used to
do that through four different mechanisms at four different places. This refactor
makes every place use the SAME operation — multiply each neuron by a learned gain
and add a learned offset, the technique called FiLM — and makes each place
switchable from the config file (`modulation.sites.{encoder,rnn,actor,critic}`).

The two promises these tests defend:
  1. The UNMODULATED baseline is bit-identical to what it was before the
     refactor. It is the project's control condition; if it drifts, every past
     comparison silently becomes invalid.
  2. A config that asks for the OLD arrangement (encoder + task-GRU gate bias +
     temperature) gets the OLD network back, byte for byte — same parameters,
     same forward pass — so existing checkpoints still restore.

Both are pinned against `.npz` "golden fixtures" captured on the pre-refactor
code (tests/fixtures/modulation/, generated by generate_golden.py). The fixtures
come in two flavours because real runs and the fast smoke case differ: a small
"flat" encoder with no LayerNorm, and the hierarchical per-sensor encoder with
LayerNorm that every real recurrent_ppo_nmn_* config actually uses.

Plan: docs/develop/active/neuromodulation/MODULATION_SITE_REFACTOR.md
"""
