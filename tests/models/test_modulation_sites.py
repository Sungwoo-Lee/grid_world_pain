def test_no_retrace_across_steps():
    """V8 — the site enables and the mechanism selector are plain Python
    attributes, so they belong to the static half of the jit cache key. Stepping
    the model repeatedly must compile exactly once."""
    traces = []
    model = _build("flat", _mod_cfg(encoder=True, rnn=True, actor=True, critic=True,
                                    mechanism="activation", temperature=True))
    spec = golden.SPECS["flat"]
    obs = golden.fixed_observation(spec)

    @nnx.jit
    def step(m, x, h):
        traces.append(1)          # executed at TRACE time only
        return m(x, h)

    h = model.initial_state()
    for _ in range(5):
        logits, value, h, _ = step(model, obs, h)
    jax.block_until_ready(logits)
    assert len(traces) == 1, f"model retraced {len(traces)} times"
