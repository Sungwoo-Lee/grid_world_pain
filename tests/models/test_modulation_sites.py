def _mod_cfg(*, encoder=True, rnn=True, actor=False, critic=False,
             mechanism="gate_bias", temperature=True, clip=(0.5, 3.0), **over):
    cfg = {
        "type": "FiLM",
        "mod_hidden_size": 8,
        "grouping_size": 1,
        "percept_bias_init": 1.0,
        "percept_add_bias_init": 0.0,
        "memory_bias_init": 0.0,
        "memory_clip": [-2.0, 2.0],
        "sites": {"encoder": encoder, "rnn": rnn, "actor": actor, "critic": critic},
        "rnn_mechanism": mechanism,
        "temperature": ({"enabled": True, "clip": list(clip)} if temperature
                        else {"enabled": False}),
    }
    cfg.update(over)
    return cfg


def _build(mode="flat", modulation_config=None, seed=golden.SEED):
    spec = golden.SPECS[mode]
    return ActorCriticRNN(
        input_dim=spec["input_dim"],
        action_dim=spec["action_dim"],
        hidden_size=spec["hidden_size"],
        rngs=nnx.Rngs(seed),
        rnn_type="GRU",
        activation="tanh",
        modulation_config=modulation_config,
        observation_breakdown=spec["breakdown"],
        encoding_config=spec["encoding_config"],
    )


def _fixture(name):
    return np.load(os.path.join(FIXTURE_DIR, name))


def _assert_matches(ref, data, prefix):
    keys = [k for k in ref.files if k.startswith(prefix)]
    assert keys, f"fixture has no {prefix}* entries"
    assert set(keys) == {k for k in data if k.startswith(prefix)}, (
        f"{prefix} key set differs from the pre-change fixture: "
        f"{sorted(set(keys) ^ {k for k in data if k.startswith(prefix)})}"
    )
    for k in keys:
        assert np.array_equal(ref[k], data[k]), f"{k} is not bit-identical"


