def test_action_shift_matches_sheeprl():
    """action_shift agrees with sheeprl@33b6366 to < 1e-6 (exact equality expected).

    Protocol:
      1. Load fixture with actions[T=5, B=4, A=3] and the pre-computed
         sheeprl reference output (torch.cat zeros[:1] + actions[:-1]).
      2. Run action_shift(actions) and compare against torch_out_shifted.

    Structural assertions checked alongside the numerical comparison:
      - output.shape == (T, B, A)
      - output[0] == 0 (first time-step is all zeros)
      - output[1:] == actions[:-1] (remaining steps match shifted input)

    T=5 chosen to expose off-by-one errors in both directions (one-step shift
    would produce [actions[0:4]] if the first-zero prepend was skipped).

    Ported from sheeprl@33b6366:sheeprl/algos/dreamer_v3/dreamer_v3.py:L102-L104
    CP2b Lever-A test (§S2 action-shift wiring).
    """
    f = _load("action_shift_input.npz")

    T = int(f["T"])
    B = int(f["B"])
    A = int(f["A"])
    actions_np      = f["actions"]           # [T, B, A]
    torch_out_np    = f["torch_out_shifted"] # [T, B, A]

    actions_jax = jnp.asarray(actions_np)
    jax_out = action_shift(actions_jax)      # [T, B, A]

    # Shape check
    assert jax_out.shape == (T, B, A), (
        f"action_shift output shape {jax_out.shape} != expected ({T}, {B}, {A})"
    )

    # Structural checks
    assert jnp.all(jax_out[0] == 0.0), (
        "action_shift: first time-step must be all zeros (no prior action). "
        f"Got jax_out[0] = {jax_out[0]}"
    )
    first_step_diff = float(jnp.max(jnp.abs(jax_out[1:] - actions_jax[:-1])))
    assert first_step_diff < THRESHOLD, (
        f"action_shift: shifted[1:] != actions[:-1] by {first_step_diff:.3e}. "
        "This is an off-by-one in the shift direction."
    )

    # Numerical parity against sheeprl reference
    max_abs_diff = float(jnp.max(jnp.abs(jax_out - jnp.asarray(torch_out_np))))
    assert max_abs_diff < THRESHOLD, (
        f"action_shift deviates from sheeprl reference by {max_abs_diff:.3e} "
        f"(threshold {THRESHOLD:.1e}). "
        f"Expected exact equality (pure arithmetic, no floating-point ops). "
        f"Log in DEVIATION_LOG.md before proceeding."
    )


