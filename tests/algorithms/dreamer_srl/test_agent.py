def test_zero_init_reward_head_matches_sheeprl():
    """RewardHead output linear kernel + bias are all-zeros (cascade fix #27).

    Protocol:
      1. Load fixture with in_features, out_features, and torch_kernel/torch_bias
         (both all-zeros — sheeprl applies uniform_init_weights(scale=0.0)).
      2. Instantiate RewardHead, which internally applies zero-init via
         uniform_init_weights(0.0, in_features, out_features, key).
      3. Assert JAX kernel and bias match the all-zeros reference at max_abs_diff=0.0.

    Zero is zero on both platforms — no platform-ULP deviation expected.
    No deviation log entry is needed; threshold is the default 1e-6.

    Sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/agent.py:L1175
    CP3 Lever-A test (cascade fix #27).
    """
    f = _load("zero_init_reward_head_input.npz")

    in_features  = int(f["in_features"])
    out_features = int(f["out_features"])
    torch_kernel = f["torch_kernel"]  # [in_features, out_features] all-zeros
    torch_bias   = f["torch_bias"]    # [out_features] all-zeros

    # Build JAX RewardHead — __init__ applies zero-init internally
    key  = jax.random.PRNGKey(0xD3EAF)
    rngs = nnx.Rngs(jax.random.PRNGKey(0))
    head = RewardHead(in_features=in_features, out_features=out_features, key=key, rngs=rngs)

    jax_kernel = jnp.asarray(head.output_linear.kernel[...])  # [in_features, out_features]
    jax_bias   = jnp.asarray(head.output_linear.bias[...])    # [out_features]

    # Shape checks
    assert jax_kernel.shape == (in_features, out_features), (
        f"RewardHead kernel shape {jax_kernel.shape} != ({in_features}, {out_features})"
    )
    assert jax_bias.shape == (out_features,), (
        f"RewardHead bias shape {jax_bias.shape} != ({out_features},)"
    )

    # Kernel: all-zeros (zero-init, cascade fix #27)
    kernel_diff = float(jnp.max(jnp.abs(jax_kernel - jnp.asarray(torch_kernel))))
    assert kernel_diff < THRESHOLD, (
        f"RewardHead kernel deviates by {kernel_diff:.3e} (threshold {THRESHOLD:.1e}). "
        f"Expected all-zeros from uniform_init_weights(scale=0.0). "
        f"Zero is zero on both platforms — no D-### deviation applies. "
        f"Log in DEVIATION_LOG.md before proceeding."
    )

    # Bias: all-zeros
    bias_diff = float(jnp.max(jnp.abs(jax_bias - jnp.asarray(torch_bias))))
    assert bias_diff < THRESHOLD, (
        f"RewardHead bias deviates by {bias_diff:.3e} (threshold {THRESHOLD:.1e}). "
        f"Expected all-zeros (bias initialized to jnp.zeros). "
        f"Log in DEVIATION_LOG.md before proceeding."
    )


