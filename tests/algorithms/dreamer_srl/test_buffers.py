def test_buffer_indexed_sample_matches_sheeprl():
    """Pre-compute sheeprl's sample-index sequence, apply both buffers' index-selection path.

    Bypasses PRNG entirely — pre-computed start_idxes and env_idxes from
    sheeprl's RNG are stored in the fixture. Our JAX buffer's
    _sample_at_indices() receives the same indices. Assert byte-identical output.

    Catches: any _get_samples reshape/tile/flatten divergence from sheeprl.
    The PRNG divergence (D-002) is bypassed — this is the testable part.

    CP3b Lever-A test 2.
    Sheeprl source: vendor/sheeprl/sheeprl/data/buffers.py:L467-L526
    """
    f = _load("buffer_sample_at_indices_matches_sheeprl_input.npz")

    buffer_size = int(f["buffer_size"])
    n_envs = int(f["n_envs"])
    n_steps = int(f["n_steps"])
    sequence_length = int(f["sequence_length"])
    batch_size = int(f["batch_size"])
    n_samples = int(f["n_samples"])
    precomputed_start_idxes = f["precomputed_start_idxes"].astype(np.intp)
    precomputed_env_idxes = f["precomputed_env_idxes"].astype(np.intp)

    step_keys = ["observations", "actions", "rewards", "terminated", "truncated", "is_first"]

    # Reconstruct the same buffer
    jax_rb = SequentialReplayBuffer(buffer_size=buffer_size, n_envs=n_envs)
    for i in range(n_steps):
        step = {}
        for k in step_keys:
            arr = f[f"step_{k}"]  # shape [n_steps, 1, n_envs, ...]
            step[k] = arr[i]
        jax_rb.add(step)

    # Call _sample_at_indices with the pre-computed indices
    jax_samples = jax_rb._sample_at_indices(
        precomputed_start_idxes=precomputed_start_idxes,
        env_idxes=precomputed_env_idxes,
        sequence_length=sequence_length,
        batch_size=batch_size,
        n_samples=n_samples,
    )

    # Compare against sheeprl reference
    for k in step_keys:
        sheeprl_sample = np.asarray(f[f"sheeprl_sample_{k}"])
        jax_sample = jax_samples[k]
        assert jax_sample.shape == sheeprl_sample.shape, (
            f"Shape mismatch for '{k}': jax={jax_sample.shape}, sheeprl={sheeprl_sample.shape}"
        )
        max_abs_diff = float(np.max(np.abs(jax_sample - sheeprl_sample)))
        assert max_abs_diff < THRESHOLD, (
            f"_sample_at_indices output diverges for '{k}': "
            f"max_abs_diff={max_abs_diff:.3e} >= {THRESHOLD:.1e}"
        )


