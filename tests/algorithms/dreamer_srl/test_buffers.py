# Test 6: cadence_env_grad_step_trace_5000_iters
# ---------------------------------------------------------------------------

def test_env_grad_step_trace_matches_sheeprl():
    """For a fixed seed + XS config, assert (env_step, grad_step, per_rank_gradient_steps)
    trace is bit-identical to sheeprl for 5000 iterations.

    Catches the 16× replay-ratio-class divergence at design time:
    if Ratio semantics, learning_starts arithmetic, or prefill_steps are wrong,
    the cumulative grad_step count will diverge from sheeprl's.

    The trace is compared against the pre-computed sheeprl reference in the fixture
    (generated by gen_cp3b_fixtures.py using sheeprl's Ratio class directly).

    CP3b Lever-A test 6 (cadence sub-gate).
    Sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L505-L515,
                    L550-L551, L661-L662
    """
    f = _load("cadence_env_grad_step_trace_5000_iters_input.npz")

    num_envs = int(f["num_envs"])
    world_size = int(f["world_size"])
    total_iters = int(f["total_iters"])
    replay_ratio = float(f["replay_ratio"])
    learning_starts_steps = int(f["learning_starts_steps"])
    per_rank_pretrain_steps = int(f["per_rank_pretrain_steps"])
    expected_trace = f["expected_trace"]  # shape [total_iters, 3]: (env_step, grad_step, per_rank_gs)

    # Replicate sheeprl cadence arithmetic using our Ratio class
    # Ref: dreamer_v3.py:L505-L515
    policy_steps_per_iter = int(num_envs * world_size)  # = 1
    learning_starts = learning_starts_steps // policy_steps_per_iter  # = 1024
    prefill_steps = learning_starts - int(learning_starts > 0)  # = 1023

    ratio = Ratio(replay_ratio, pretrain_steps=per_rank_pretrain_steps)

    policy_step = 0
    cumulative_grad_steps = 0
    jax_trace = []

    for iter_num in range(1, total_iters + 1):
        policy_step += policy_steps_per_iter

        per_rank_gradient_steps = 0
        if iter_num >= learning_starts:
            # Ref: dreamer_v3.py:L661-L662
            ratio_steps = policy_step - prefill_steps * policy_steps_per_iter
            per_rank_gradient_steps = ratio(ratio_steps / world_size)
            cumulative_grad_steps += per_rank_gradient_steps

        jax_trace.append((policy_step, cumulative_grad_steps, per_rank_gradient_steps))

    jax_trace_arr = np.array(jax_trace, dtype=np.int64)

    assert jax_trace_arr.shape == expected_trace.shape, (
        f"Trace shape mismatch: jax={jax_trace_arr.shape}, expected={expected_trace.shape}"
    )

    # Bit-identical check
    mismatch = np.where(jax_trace_arr != expected_trace)
    if len(mismatch[0]) > 0:
        first_mismatch = mismatch[0][0]
        col_names = ["env_step", "grad_step", "per_rank_gradient_steps"]
        col = mismatch[1][0]
        pytest.fail(
            f"Cadence trace diverges from sheeprl at iter {first_mismatch + 1}, "
            f"column '{col_names[col]}': "
            f"jax={jax_trace_arr[first_mismatch, col]}, "
            f"sheeprl={expected_trace[first_mismatch, col]}\n"
            f"First 5 jax:     {jax_trace_arr[:5].tolist()}\n"
            f"First 5 sheeprl: {expected_trace[:5].tolist()}\n"
            "HALT: This is the 16x replay-ratio-class divergence. "
            "Do not relax threshold — investigate the root cause."
        )
