def test_parallel_env_lane_non_interference():
    """Add 200 transitions across 4 envs. Assert no cross-lane leakage.

    Env 0's obs are all 1.0, env 1's all 2.0, etc.
    Sample contiguous windows from each lane (using _sample_at_indices with
    env_idxes locked to one lane). Assert every obs value in the window
    matches that lane's sentinel value.

    Catches: any cross-env buffer leakage from incorrect n_envs striding.

    CP3b Lever-A test 4.
    Sheeprl source: vendor/sheeprl/sheeprl/data/buffers.py:L480-L489
    """
    f = _load("buffer_parallel_env_lane_non_interference_input.npz")

    buffer_size = int(f["buffer_size"])
    n_envs = int(f["n_envs"])
    n_steps = int(f["n_steps"])
    sequence_length = int(f["sequence_length"])
    n_windows = int(f["n_windows"])

    step_keys = ["observations", "actions", "rewards", "terminated", "truncated", "is_first"]

    # Rebuild JAX buffer
    jax_rb = SequentialReplayBuffer(buffer_size=buffer_size, n_envs=n_envs)
    for i in range(n_steps):
        step = {}
        for k in step_keys:
            arr = f[f"step_{k}"]  # shape [n_steps, 1, n_envs, ...]
            step[k] = arr[i]
        jax_rb.add(step)

    # Sample n_windows windows from each lane with a deterministic start
    # (start_idxes must be valid: [0 .. pos - seq_len])
    max_start = jax_rb._pos - sequence_length  # = 50 - 8 = 42
    start_idxes = np.arange(0, min(n_windows, max_start + 1), dtype=np.intp)

    for env_idx in range(n_envs):
        sentinel = float(env_idx + 1)
        env_idxes = np.full(len(start_idxes), env_idx, dtype=np.intp)

        samples = jax_rb._sample_at_indices(
            precomputed_start_idxes=start_idxes,
            env_idxes=env_idxes,
            sequence_length=sequence_length,
            batch_size=len(start_idxes),
            n_samples=1,
        )

        obs = samples["observations"]  # shape [1, seq_len, batch, obs_dim]
        obs_flat = obs.ravel()
        assert np.allclose(obs_flat, sentinel), (
            f"Env lane {env_idx} (sentinel={sentinel}) has contaminated obs. "
            f"Unique values found: {np.unique(obs_flat)}"
        )


