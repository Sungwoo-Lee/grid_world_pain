"""CP3b state-evolution bit-identity tests for src/algorithms/dreamer_srl/buffers.py.

CP3b tests state-evolution bit-identity, NOT pure-function bit-identity.
Pure-function identity is impossible here because PyTorch and JAX use different
PRNG streams (D-002 class). Instead these tests:

  - Drive both buffers with an identical deterministic add() sequence and
    compare stored state byte-for-byte.
  - Pre-compute sheeprl's sample-index sequence, pass it to both buffers'
    _sample_at_indices() method, and compare byte-for-byte.
  - Verify is_first marker placement in straddling windows.
  - Verify parallel-env lane non-interference.
  - Verify YAML cadence keys match sheeprl XS defaults.
  - Verify (env_step, grad_step) trace is bit-identical to sheeprl for 5000 iters.

The fixtures are generated by scripts/fixtures/gen_cp3b_fixtures.py (requires
sheeprl_bridge env with PyTorch). Tests run in grid_world_pain env (no PyTorch
needed) and compare against pre-stored reference values.

Run with:
    /home/vncuser/miniconda3/envs/grid_world_pain/bin/python \\
        -m pytest tests/algorithms/dreamer_srl/test_buffers.py -v

DEVIATION NOTES:
  D-004: memmap / memmap_dir / memmap_mode are omitted from the JAX buffer.
    In-memory storage only. See DEVIATION_LOG.md.
"""
import os
import sys

import numpy as np
import pytest
import yaml

_REPO_ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
)
sys.path.insert(0, _REPO_ROOT)

from src.algorithms.dreamer_srl.buffers import SequentialReplayBuffer
from src.algorithms.dreamer_srl.utils import Ratio

FIXTURE_DIR = os.path.join(_REPO_ROOT, "tests", "fixtures", "dreamer_srl")
THRESHOLD = 1e-6


def _load(name: str) -> np.lib.npyio.NpzFile:
    path = os.path.join(FIXTURE_DIR, name)
    if not os.path.exists(path):
        pytest.skip(f"Fixture not found: {path}. Run scripts/fixtures/gen_cp3b_fixtures.py first.")
    return np.load(path)


# ---------------------------------------------------------------------------
# Test 1: buffer_storage_state_after_deterministic_adds
# ---------------------------------------------------------------------------

def test_buffer_state_evolution_matches_sheeprl():
    """Drive our JAX buffer with the same add() sequence as sheeprl.

    Both buffers receive the same 100-step add() sequence from fixture.
    Assert byte-identical storage state (_buf, _pos, _full).

    Catches: any add() ring-buffer arithmetic divergence from sheeprl.

    CP3b Lever-A test 1.
    Sheeprl source: vendor/sheeprl/sheeprl/data/buffers.py:L145-L221
    """
    f = _load("buffer_storage_state_after_deterministic_adds_input.npz")

    buffer_size = int(f["buffer_size"])
    n_envs = int(f["n_envs"])
    n_steps = int(f["n_steps"])
    expected_pos = int(f["sheeprl_pos"])
    expected_full = bool(f["sheeprl_full"])

    # Reconstruct the step sequence
    step_keys = ["observations", "actions", "rewards", "terminated", "truncated", "is_first"]
    steps = []
    for i in range(n_steps):
        step = {}
        for k in step_keys:
            arr = f[f"step_{k}"]  # shape [n_steps, 1, n_envs, ...]
            step[k] = arr[i]  # shape [1, n_envs, ...]
        steps.append(step)

    # Drive our JAX buffer
    jax_rb = SequentialReplayBuffer(buffer_size=buffer_size, n_envs=n_envs)
    for step in steps:
        jax_rb.add(step)

    # Assert metadata matches
    assert jax_rb._pos == expected_pos, f"_pos mismatch: got {jax_rb._pos}, expected {expected_pos}"
    assert jax_rb._full == expected_full, f"_full mismatch: got {jax_rb._full}, expected {expected_full}"

    # Assert stored buffer arrays are byte-identical in the FILLED region.
    # Both buffers allocate with np.empty so the unfilled portion [_pos:] is
    # uninitialized garbage — we compare only [:_pos] which has been written.
    for k in step_keys:
        sheeprl_arr = np.asarray(f[f"buf_{k}"])  # shape [buffer_size, n_envs, ...]
        jax_arr = jax_rb._buf[k]
        assert jax_arr.shape == sheeprl_arr.shape, (
            f"Shape mismatch for '{k}': jax={jax_arr.shape}, sheeprl={sheeprl_arr.shape}"
        )
        # Compare only the filled region (semantically equivalent to sheeprl)
        n_filled = expected_pos  # _pos == number of steps added when _full is False
        sheeprl_filled = sheeprl_arr[:n_filled]
        jax_filled = jax_arr[:n_filled]
        max_abs_diff = float(np.max(np.abs(jax_filled - sheeprl_filled)))
        assert max_abs_diff < THRESHOLD, (
            f"Buffer state diverges for '{k}' (filled region [:{ n_filled}]): "
            f"max_abs_diff={max_abs_diff:.3e} >= {THRESHOLD:.1e}"
        )


