def test_is_first_marker_at_done_boundary():
    """Assert is_first=1 lands at the correct time index in a straddling window.

    A buffer is constructed with a done at step DONE_AT and is_first=1 at
    step DONE_AT+1. A window starting at START_IDX straddles the boundary.
    Assert:
      (a) JAX output is byte-identical to sheeprl's.
      (b) is_first[expected_offset] == 1 and all others are 0.

    This catches the silently-dead-CP4b-code-path failure mode: if is_first
    placement diverges, CP4b's three-quantity reset never fires in practice.

    CP3b Lever-A test 3.
    Sheeprl source: vendor/sheeprl/sheeprl/data/buffers.py:L395-L526
    """
    f = _load("buffer_is_first_marker_placement_in_straddling_window_input.npz")

    buffer_size = int(f["buffer_size"])
    n_envs = int(f["n_envs"])
    n_steps = int(f["n_steps"])
    start_idx = int(f["start_idx"])
    sequence_length = int(f["sequence_length"])
    is_first_expected_offset = int(f["is_first_expected_offset"])

    step_keys = ["observations", "actions", "rewards", "terminated", "truncated", "is_first"]

    # Reconstruct JAX buffer with the same step sequence
    jax_rb = SequentialReplayBuffer(buffer_size=buffer_size, n_envs=n_envs)
    for i in range(n_steps):
        step = {}
        for k in step_keys:
            arr = f[f"step_{k}"]  # shape [n_steps, 1, 1, ...]
            step[k] = arr[i]
        jax_rb.add(step)

    # Force-sample the straddling window
    start_idx_arr = np.array([start_idx], dtype=np.intp)
    env_idxes_arr = np.array([0], dtype=np.intp)

    jax_samples = jax_rb._sample_at_indices(
        precomputed_start_idxes=start_idx_arr,
        env_idxes=env_idxes_arr,
        sequence_length=sequence_length,
        batch_size=1,
        n_samples=1,
    )

    # (a) Byte-identical to sheeprl
    for k in step_keys:
        sheeprl_sample = np.asarray(f[f"sheeprl_sample_{k}"])
        jax_sample = jax_samples[k]
        assert jax_sample.shape == sheeprl_sample.shape, (
            f"Shape mismatch for '{k}': jax={jax_sample.shape}, sheeprl={sheeprl_sample.shape}"
        )
        max_abs_diff = float(np.max(np.abs(jax_sample - sheeprl_sample)))
        assert max_abs_diff < THRESHOLD, (
            f"Straddling window diverges for '{k}': "
            f"max_abs_diff={max_abs_diff:.3e} >= {THRESHOLD:.1e}"
        )

    # (b) is_first placement
    # jax_samples["is_first"] shape: [1, seq_len, 1, 1]
    is_first_window = jax_samples["is_first"].ravel()  # shape [seq_len]
    assert is_first_window[is_first_expected_offset] == 1.0, (
        f"is_first=1 not at expected offset {is_first_expected_offset}: {is_first_window}"
    )
    for i, val in enumerate(is_first_window):
        if i != is_first_expected_offset:
            assert val == 0.0, (
                f"Unexpected is_first=1 at offset {i}: {is_first_window}"
            )


