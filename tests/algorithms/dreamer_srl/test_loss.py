def test_twohot_log_prob_matches_sheeprl():
    """Verify log_prob(target) for [T=4, B=16, 1] targets matches sheeprl output.

    Lever A test for CP5 function 'twohot_log_prob'.
    Sheeprl source: vendor/sheeprl/sheeprl/utils/distribution.py:L253-L276

    This test exercises both the encoding (Test 2 prerequisite) AND the
    log-pred computation (logsumexp normalization + cross-entropy reduction).
    If the log_prob matches sheeprl exactly, both the symlog-space bin lookup
    AND the log-probability arithmetic are correct.

    Expected shape: [T=4, B=16] (event dim dims=1 reduced out).
    Expected max_abs_diff < 1e-6 (no D-class deviation anticipated).
    """
    fixture = _load("twohot_log_prob_input.npz")
    logits_np = fixture["logits"]           # [T=4, B=16, 255]
    targets_np = fixture["targets"]         # [T=4, B=16, 1]
    torch_log_prob = fixture["torch_out_log_prob"]  # [T=4, B=16]

    logits_jax = jnp.asarray(logits_np)
    targets_jax = jnp.asarray(targets_np)

    jax_dist = TwoHotEncoding(logits_jax, dims=1, low=-20, high=20)
    jax_log_prob = jax_dist.log_prob(targets_jax)  # [T, B]

    # Shape check
    assert jax_log_prob.shape == torch_log_prob.shape, (
        f"Shape mismatch: jax={jax_log_prob.shape} torch={torch_log_prob.shape}. "
        f"dims=1 must reduce the event dimension [T,B,1] → [T,B]."
    )

    # D-006: linspace ULP cascades from bins → encode → log_prob sum.
    # Expected max_abs_diff ~1.8e-5 (relative: 2.4e-6 — float32 platform drift).
    # Threshold THRESHOLD_D006=3e-5. Pending PI sign-off at CP5 gate.
    max_abs_diff = float(jnp.max(jnp.abs(jax_log_prob - jnp.asarray(torch_log_prob))))
    assert max_abs_diff < THRESHOLD_D006, (
        f"twohot_log_prob max_abs_diff={max_abs_diff:.3e} exceeds D-006 threshold {THRESHOLD_D006:.1e}. "
        f"Expected ~1.8e-5 (D-006 float32 linspace ULP cascade). "
        f"Check: (1) symlog applied to x before bin lookup, (2) bins in symlog space, "
        f"(3) logsumexp normalization matches sheeprl L275. "
        f"Log in DEVIATION_LOG.md if unavoidable."
    )


