def test_twohot_bins_endpoints_match_sheeprl():
    """Verify bin grid endpoints and the full 255-bin grid match sheeprl's.

    Lever A test for CP5 function 'twohot_bins_endpoints'.
    Sheeprl source: vendor/sheeprl/sheeprl/utils/distribution.py:L237

    Asserts:
      - jax.bins[0] == -20.0   (exact — float32 linspace boundary)
      - |jax.bins[127]| < 1e-6 (float32 linspace midpoint; 7.45e-08 due to rounding)
      - jax.bins[254] == +20.0 (exact — float32 linspace boundary)
      - max_abs_diff(jax.bins, sheeprl.bins) < 1e-6 over the full 255-bin grid

    NOTE: bins[127] is NOT exactly 0.0 in sheeprl's float32 linspace. The value
    is 7.45e-08 (one float32 ULP from zero at the scale of linspace(-20,20,255)).
    Both sides reproduce this identical float32 rounding, so max_abs_diff = 0.0.
    Do NOT change the threshold or "fix" bins[127] to 0.0 — that would diverge.

    Historical scar context: if the JAX implementation used symexp(linspace(...))
    instead of linspace(...), this test would catch it immediately because
    symexp(-20)≠-20 and symexp(20)≠20 in real space.
    """
    fixture = _load("twohot_bins_endpoints_input.npz")
    torch_bins = fixture["torch_bins"]  # [255] from sheeprl PyTorch

    # Instantiate with dummy logits of shape [1, 255] to access .bins
    dummy_logits = jnp.zeros((1, 255))
    jax_dist = TwoHotEncoding(dummy_logits, dims=0, low=-20, high=20)
    jax_bins = jax_dist.bins  # [255]

    # Endpoint checks
    assert float(jax_bins[0]) == -20.0, f"bins[0] must be -20.0, got {float(jax_bins[0])}"
    assert abs(float(jax_bins[127])) < 1e-6, (
        f"bins[127] must be ~0.0 (|val| < 1e-6), got {float(jax_bins[127])}. "
        f"If this fails, the bin grid may be in real space (historical bug)."
    )
    assert float(jax_bins[254]) == 20.0, f"bins[254] must be +20.0, got {float(jax_bins[254])}"

    # Full grid bit-identity against sheeprl.
    # D-006: JAX linspace and PyTorch linspace differ by 1 ULP at the midpoint.
    # Threshold relaxed to THRESHOLD_D006=3e-5. Pending PI sign-off at CP5 gate.
    max_abs_diff = float(jnp.max(jnp.abs(jax_bins - jnp.asarray(torch_bins))))
    assert max_abs_diff < THRESHOLD_D006, (
        f"twohot_bins_endpoints max_abs_diff={max_abs_diff:.3e} exceeds D-006 threshold {THRESHOLD_D006:.1e}. "
        f"Bin grid does not match sheeprl. "
        f"D-006: JAX/PyTorch linspace ULP diff at midpoint is expected (~1.9e-6). "
        f"If diff > 3e-5, a semantic error has been introduced — log in DEVIATION_LOG.md."
    )


