def test_loss_module_does_not_import_from_src_models():
    """Verify loss.py does not import from src.models (isolation rule).

    Imports from src.models.dreamer_v3_* are forbidden in src/algorithms/dreamer_srl/
    (v2 Risks §13). The historical bug in part arose from pattern-matching against
    the in-house code that had bins in real reward space.
    """
    import importlib
    import importlib.util
    import ast

    loss_path = os.path.join(_REPO_ROOT, "src", "algorithms", "dreamer_srl", "loss.py")
    with open(loss_path) as f:
        source = f.read()

    tree = ast.parse(source)
    forbidden_imports = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            if isinstance(node, ast.ImportFrom) and node.module:
                if "src.models.dreamer_v3" in node.module:
                    forbidden_imports.append(node.module)
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    if "src.models.dreamer_v3" in alias.name:
                        forbidden_imports.append(alias.name)

    assert not forbidden_imports, (
        f"loss.py imports from forbidden modules: {forbidden_imports}. "
        f"Isolation rule (v2 Risks §13): src/algorithms/dreamer_srl/ must not "
        f"import from src.models.dreamer_v3_*."
    )


# Guard against symexp-at-storage regression
def test_bins_not_symexp_at_storage():
    """Verify bins are NOT symexp-transformed at storage time.

    The historical bug stored self.bins = symexp(linspace(-20, 20, 255)).
    This test catches that recurrence: if symexp were applied at storage,
    bins[0] would be symexp(-20) ≈ -485165195 not -20.0.

    This test is structurally redundant with test_twohot_bins_endpoints_match_sheeprl
    but makes the historical-bug-prevention intent explicit.
    """
    dummy_logits = jnp.zeros((1, 255))
    jax_dist = TwoHotEncoding(dummy_logits, dims=0, low=-20, high=20)

    # If symexp were applied at storage: symexp(-20) ≈ -485165195
    # If bins are in symlog space: bins[0] = -20.0
    assert abs(float(jax_dist.bins[0]) - (-20.0)) < 1e-6, (
        f"bins[0] = {float(jax_dist.bins[0]):.6f}, expected -20.0. "
        f"If this is ~-485165195, symexp was incorrectly applied at storage — "
        f"that is the historical bug. bins must stay in symlog space."
    )
    assert abs(float(jax_dist.bins[254]) - 20.0) < 1e-6, (
        f"bins[254] = {float(jax_dist.bins[254]):.6f}, expected +20.0. "
        f"If this is ~+485165195, symexp was incorrectly applied at storage."
    )


