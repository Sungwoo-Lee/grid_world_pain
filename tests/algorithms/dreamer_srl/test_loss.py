FIXTURE_DIR = os.path.join(_REPO_ROOT, "tests", "fixtures", "dreamer_srl")
THRESHOLD = 1e-6  # default Lever A threshold

# D-006: JAX jnp.linspace vs PyTorch torch.linspace ULP difference.
# bins[127]: JAX=0.0 exactly, PyTorch=7.45e-8 (1 ULP at the midpoint step 40/254*127).
# This cascades: bins max_abs_diff=1.9e-6, encode=6.1e-6, log_prob=1.8e-5.
# Relative max diff for log_prob: 2.4e-6 — float32 linspace + arithmetic platform drift.
# Threshold relaxed to 3e-5 (same order as D-003 symexp ULP drift).
# Pending PI sign-off at CP5 gate. See DEVIATION_LOG.md D-006.
THRESHOLD_D006 = 3e-5


def _load(name: str) -> np.lib.npyio.NpzFile:
    path = os.path.join(FIXTURE_DIR, name)
    if not os.path.exists(path):
        pytest.skip(f"Fixture not found: {path}. Run scripts/fixtures/gen_cp5_fixtures.py first.")
    return np.load(path)


