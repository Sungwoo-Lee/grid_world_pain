"""CP5 bit-identity tests for src/algorithms/dreamer_srl/loss.py.

Tests the TwoHotEncoding class ported from
sheeprl@33b6366:sheeprl/utils/distribution.py:L224-L276.

Each test asserts that the JAX implementation agrees with the pre-computed
sheeprl@33b6366 PyTorch reference (stored in tests/fixtures/dreamer_srl/*.npz)
to within 1e-6 max-absolute-difference (Lever A in
docs/develop/active/dreamer_srl_v3/IMPLEMENTATION_PLAN.md).

The fixtures are generated by scripts/fixtures/gen_cp5_fixtures.py which runs
in the sheeprl_bridge env (has PyTorch). The tests here run in the grid_world_pain
env (JAX only) and compare against the pre-stored torch_out values.

Run with:
    /home/vncuser/miniconda3/envs/grid_world_pain/bin/python \\
        -m pytest tests/algorithms/dreamer_srl/test_loss.py -v

HISTORICAL SCAR — WHY THESE TESTS EXIST
-----------------------------------------
During the v1 cascade debugging (pre-2026-05-12), the bin grid was implemented
in real reward space (self.bins = symexp(linspace(-20, 20, 255))). Losses
decreased but to the wrong basin. Static plan review (three reviewers, 1056-line
spec) did not catch it. test_twohot_encode_matches_sheeprl (Test 2) with a
non-trivial target (e.g. target=0.5, symlog(0.5)≈0.405) would have caught the
bug on the first run: the bin indices would be wrong, the two-hot weights would
differ, and log_prob would mismatch by orders of magnitude.

SYMLOG-SPACE BIN DISCIPLINE
----------------------------
The bin grid linspace(-20, 20, 255) is stored in SYMLOG SPACE. symexp is applied
ONLY at consumption (mean/mode), never to the stored grid. Targets are
symlog-encoded BEFORE bin lookup inside log_prob. All three tests verify this
discipline holds.

THRESHOLD NOTE
--------------
Two-hot encoding is integer-arithmetic-heavy (one_hot scatter + integer bin
indices). The expected max_abs_diff is well below 1e-6. No deviation-log entry
is expected. If any test exceeds 1e-6 and it is not a platform float32 ULP
issue, the deviation must be logged in DEVIATION_LOG.md before proceeding.
"""
