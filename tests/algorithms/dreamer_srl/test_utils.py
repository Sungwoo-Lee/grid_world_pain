# uniform_init_weights — distribution property test (DEVIATION D-002)
# ---------------------------------------------------------------------------

def test_uniform_init_weights_matches_sheeprl():
    """Distribution property test for uniform_init_weights (DEVIATION D-002).

    Verifies shape and that all values are within the theoretical [-limit, +limit]
    bounds. The scale=0.0 (zero-init) case is implicitly tested by checking
    limit → 0 (kernel = all zeros). Logged as DEVIATION D-002 in DEVIATION_LOG.md.

    sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/utils.py:L170-L186
    Fixture: tests/fixtures/dreamer_srl/uniform_init_weights_input.npz
    """
    fixture = _load("uniform_init_weights_input.npz")
    in_features = int(fixture["in_features"])
    out_features = int(fixture["out_features"])
    given_scale = float(fixture["given_scale"])
    limit = float(fixture["limit"])

    key = jax.random.PRNGKey(int(fixture["jax_seed"]))
    jax_kernel = uniform_init_weights(given_scale, in_features, out_features, key)

    assert jax_kernel.shape == (in_features, out_features), (
        f"shape mismatch: got {jax_kernel.shape}, expected ({in_features}, {out_features})"
    )
    max_abs_val = float(jnp.max(jnp.abs(jax_kernel)))
    assert max_abs_val <= limit + 1e-5, (
        f"uniform_init_weights value {max_abs_val:.6f} exceeds limit {limit:.6f}"
    )

    # Additional test: zero-init case (given_scale=0.0) must produce all-zeros
    key2 = jax.random.PRNGKey(42)
    zero_kernel = uniform_init_weights(0.0, in_features, out_features, key2)
    assert jnp.all(zero_kernel == 0.0), "uniform_init_weights(0.0) must be exactly zero"


