def test_moments_update_matches_sheeprl():
    """Bit-identity test for moments_update (with DEVIATION D-001 note).

    Sheeprl's Moments.forward calls fabric.all_gather (a no-op on single-process).
    Our JAX port skips the all_gather. The pre-computed torch_out in the fixture
    was generated WITHOUT all_gather so both sides should match.
    Logged as DEVIATION D-001 in DEVIATION_LOG.md.

    sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/utils.py:L40-L63
    Fixture: tests/fixtures/dreamer_srl/moments_update_input.npz
    """
    fixture = _load("moments_update_input.npz")
    x_np = fixture["x"]
    decay = float(fixture["decay"])
    max_ = float(fixture["max_"])
    percentile_low = float(fixture["percentile_low"])
    percentile_high = float(fixture["percentile_high"])
    torch_offset = fixture["torch_out_offset"]
    torch_invscale = fixture["torch_out_invscale"]

    state = moments_init(decay=decay, max_=max_,
                         percentile_low=percentile_low, percentile_high=percentile_high)
    new_state, jax_offset, jax_invscale = moments_update(
        state, jnp.asarray(x_np),
        decay=decay, max_=max_,
        percentile_low=percentile_low, percentile_high=percentile_high,
    )

    diff_offset = float(abs(float(jax_offset) - float(torch_offset)))
    diff_invscale = float(abs(float(jax_invscale) - float(torch_invscale)))
    assert diff_offset < THRESHOLD, (
        f"moments_update offset deviates by {diff_offset:.3e} (threshold {THRESHOLD:.1e})"
    )
    assert diff_invscale < THRESHOLD, (
        f"moments_update invscale deviates by {diff_invscale:.3e} (threshold {THRESHOLD:.1e})"
    )


