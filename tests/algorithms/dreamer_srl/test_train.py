def test_polyak_subsequent_call_blend():
    """Subsequent Polyak calls with tau=0.02 produce EMA blend of online → target.

    For subsequent gradient steps (cumulative_steps > 0), sheeprl uses tau=0.02
    (the XS default cfg.algo.critic.tau):
        target = (1 - tau) * target + tau * online
               = 0.98 * target + 0.02 * online

    This test:
      1. Loads online and target params with DIFFERENT values.
      2. Calls polyak_update(online, target, tau=0.02).
      3. Asserts result matches 0.98*target + 0.02*online to within 1e-6.
      4. Cross-checks against pre-computed PyTorch reference.

    Sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L678-L680
        tau = cfg.algo.critic.tau  (= 0.02 for subsequent calls in XS config)
        for cp, tcp in zip(critic.module.parameters(), target_critic.parameters()):
            tcp.data.copy_(tau * cp.data + (1 - tau) * tcp.data)
        = 0.02 * online + 0.98 * target

    NOTE: sheeprl writes `tau * cp + (1-tau) * tcp` (online first); we write
    `(1-tau) * target + tau * online` (equivalent formula, same result).

    Threshold: strict 1e-6 (pure float32 arithmetic — no TwoHotEncoding cascade).
    """
    fixture = np.load(os.path.join(FIXTURE_DIR, "polyak_subsequent_call_input.npz"))

    tau = float(fixture["tau"])
    assert abs(tau - 0.02) < 1e-7, f"Expected tau=0.02 in subsequent-call fixture, got {tau}"

    n_groups = int(fixture["n_param_groups"])
    param_keys = sorted([k.replace("online_", "") for k in fixture.files if k.startswith("online_")])
    assert len(param_keys) == n_groups

    online_params = {k: jnp.asarray(fixture[f"online_{k}"]) for k in param_keys}
    target_params_init = {k: jnp.asarray(fixture[f"target_init_{k}"]) for k in param_keys}
    torch_out = {k: np.asarray(fixture[f"torch_out_target_{k}"]) for k in param_keys}

    # Call polyak_update with tau=0.02
    new_target = polyak_update(online_params, target_params_init, tau=0.02)

    max_diff_global = 0.0
    for k in param_keys:
        new_target_np = np.asarray(new_target[k])
        online_np = np.asarray(online_params[k])
        target_init_np = np.asarray(target_params_init[k])
        torch_ref_np = torch_out[k]

        # Check EMA formula: expected = 0.98 * target + 0.02 * online
        expected_np = 0.98 * target_init_np + 0.02 * online_np
        diff_formula = float(np.max(np.abs(new_target_np - expected_np)))
        assert diff_formula < THRESHOLD_POLYAK, (
            f"test_polyak_subsequent_call_blend FAILED for '{k}' (EMA formula check): "
            f"max_abs_diff={diff_formula:.3e} >= threshold={THRESHOLD_POLYAK:.1e}\n"
            f"  Expected: (1-0.02)*target + 0.02*online = 0.98*target + 0.02*online\n"
            f"  Sheeprl: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L679-L680\n"
            f"  JAX: src/algorithms/dreamer_srl/train.py:polyak_update (tau=0.02 case)"
        )

        # Cross-check vs torch reference
        diff_ref = float(np.max(np.abs(new_target_np - torch_ref_np)))
        max_diff_global = max(max_diff_global, diff_ref)
        assert diff_ref < THRESHOLD_POLYAK, (
            f"test_polyak_subsequent_call_blend FAILED for '{k}' (torch ref check): "
            f"max_abs_diff={diff_ref:.3e} >= threshold={THRESHOLD_POLYAK:.1e}\n"
            f"  Cross-check vs pre-computed PyTorch reference failed."
        )

    print(f"test_polyak_subsequent_call_blend PASSED")
    print(f"  tau=0.02 EMA blend: all {len(param_keys)} param groups pass formula check")
    print(f"  max_abs_diff vs torch ref = {max_diff_global:.2e} (< {THRESHOLD_POLYAK:.1e})")


