def test_critic_loss_two_terms():
    """Critic loss has BOTH terms: -log_prob(lambda_target) AND -log_prob(target_critic_value).

    Verifies cascade fix #29: the EMA slow-target self-regularization term must be
    present in the critic loss. The test confirms:
      1. Both neg_lp1 and neg_lp2 match their PyTorch references (within D-006 threshold).
      2. The combined discount-weighted scalar loss matches the PyTorch reference.

    Sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L307-L316

    If only one term is present (the historical bug), neg_lp2 would be zero and
    value_loss would be half its correct value — a clear numerical mismatch.
    """
    fixture = np.load(os.path.join(FIXTURE_DIR, "critic_loss_two_terms_input.npz"))

    qv_logits_np   = fixture["qv_logits"]    # [H, BT, 255]
    lambda_val_np  = fixture["lambda_values"]  # [H, BT, 1]
    target_val_np  = fixture["target_values"]  # [H, BT, 1]
    discount_np    = fixture["discount"]        # [H, BT]  pre-sliced + squeezed

    torch_lp1_np   = fixture["torch_out_lp1"]         # [H, BT]
    torch_lp2_np   = fixture["torch_out_lp2"]         # [H, BT]
    torch_loss     = float(fixture["torch_out_value_loss"])  # scalar

    # The fixture's discount is already [H, BT] (pre-sliced + squeezed).
    # compute_critic_loss expects discount as [H+1, BT, 1] and applies [:-1].squeeze(-1).
    # For this test we pass a wrapped discount that makes discount[:-1].squeeze(-1) == fixture discount.
    # Wrap: prepend a dummy row and add trailing dim.
    H = discount_np.shape[0]
    BT = discount_np.shape[1]
    # Extend discount: add a dummy last row so [:-1] gives us back the fixture discount.
    # shape: [H+1, BT, 1]
    dummy_row = np.zeros((1, BT), dtype=np.float32)
    discount_extended = np.concatenate([discount_np, dummy_row], axis=0)  # [H+1, BT]
    discount_extended_4d = discount_extended[:, :, np.newaxis]              # [H+1, BT, 1]

    qv_logits = jnp.asarray(qv_logits_np)
    lambda_val = jnp.asarray(lambda_val_np)
    target_val = jnp.asarray(target_val_np)
    discount_jax = jnp.asarray(discount_extended_4d)

    value_loss, neg_lp1, neg_lp2 = compute_critic_loss(
        qv_logits=qv_logits,
        lambda_values=lambda_val,
        target_critic_values=target_val,
        discount=discount_jax,
    )

    # --- Check term 1: -qv.log_prob(lambda_values)
    neg_lp1_np = np.asarray(neg_lp1)
    diff_lp1 = float(np.max(np.abs(neg_lp1_np - torch_lp1_np)))
    assert diff_lp1 < THRESHOLD_TWOHOT_LP, (
        f"test_critic_loss_two_terms FAILED on term 1 (-lp1): "
        f"max_abs_diff={diff_lp1:.3e} >= threshold={THRESHOLD_TWOHOT_LP:.1e}\n"
        f"  Sheeprl: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L314\n"
        f"  JAX: src/algorithms/dreamer_srl/train.py:compute_critic_loss (neg_lp1)\n"
        f"  NOTE: D-006 class (TwoHotEncoding linspace ULP drift). D-010 PI-ratified threshold 5e-5. "
        f"If diff > 5e-5, log new deviation D-011+ in DEVIATION_LOG.md (pending PI ratification)."
    )

    # --- Check term 2: -qv.log_prob(target_critic_values) — CASCADE FIX #29
    neg_lp2_np = np.asarray(neg_lp2)
    diff_lp2 = float(np.max(np.abs(neg_lp2_np - torch_lp2_np)))
    assert diff_lp2 < THRESHOLD_TWOHOT_LP, (
        f"test_critic_loss_two_terms FAILED on term 2 (-lp2, cascade fix #29): "
        f"max_abs_diff={diff_lp2:.3e} >= threshold={THRESHOLD_TWOHOT_LP:.1e}\n"
        f"  Sheeprl: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L315\n"
        f"  JAX: src/algorithms/dreamer_srl/train.py:compute_critic_loss (neg_lp2)\n"
        f"  CASCADE FIX #29: if neg_lp2 is all-zeros, the second term is missing!\n"
        f"  NOTE: D-006 class. D-010 PI-ratified threshold 5e-5; log D-011+ if diff > 5e-5."
    )

    # Sanity check: neg_lp2 is NOT all zeros (catches the missing-term bug)
    assert float(np.max(np.abs(neg_lp2_np))) > 0.1, (
        f"neg_lp2 appears to be all-zeros or near-zero (max={np.max(np.abs(neg_lp2_np)):.3e}). "
        f"This suggests the second term (EMA self-reg, cascade fix #29) is missing from "
        f"compute_critic_loss. Both log_prob terms are required: "
        f"-qv.log_prob(lambda_values) AND -qv.log_prob(target_critic_values)."
    )

    # --- Check scalar value_loss
    value_loss_np = float(value_loss)
    diff_loss = abs(value_loss_np - torch_loss)
    assert diff_loss < THRESHOLD_SCALAR_LOSS, (
        f"test_critic_loss_two_terms FAILED on scalar value_loss: "
        f"|jax={value_loss_np:.6f} - torch={torch_loss:.6f}| = {diff_loss:.3e} "
        f">= threshold={THRESHOLD_SCALAR_LOSS:.1e}\n"
        f"  Sheeprl: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L316\n"
        f"  JAX: src/algorithms/dreamer_srl/train.py:compute_critic_loss (value_loss)"
    )

    print(f"test_critic_loss_two_terms PASSED")
    print(f"  term1 (-lp1) max_abs_diff = {diff_lp1:.3e} (< {THRESHOLD_TWOHOT_LP:.1e})")
    print(f"  term2 (-lp2) max_abs_diff = {diff_lp2:.3e} (< {THRESHOLD_TWOHOT_LP:.1e}) — cascade fix #29 present")
    print(f"  scalar loss  abs_diff     = {diff_loss:.3e} (< {THRESHOLD_SCALAR_LOSS:.1e})")


