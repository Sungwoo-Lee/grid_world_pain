def test_critic_target_lambda():
    """Critic regresses against UN-normalised lambda_values (NOT Moments-normalised).

    Sheeprl dreamer_v3.py:L314 uses `lambda_values.detach()` directly — before
    the Moments normalization at L276-L279 (which produces `normed_lambda_values`).
    The actor uses `normed_lambda_values` for the advantage computation.
    The critic uses the raw lambda_values.

    This test verifies:
      - jax.log_prob(raw_lambda) matches the PyTorch reference (within D-006 threshold).
      - jax.log_prob(normed_lambda) does NOT match the PyTorch reference
        (the two are separated by >> 1e-4; the normed form is wrong for the critic).

    Sheeprl source: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L251-L256, L276-L279, L314
    """
    fixture = np.load(os.path.join(FIXTURE_DIR, "critic_target_lambda_input.npz"))

    qv_logits_np       = fixture["qv_logits"]      # [H, BT, 255]
    lambda_values_np   = fixture["lambda_values"]  # [H, BT, 1]  — raw (un-normalised)
    normed_lambda_np   = fixture["normed_lambda"]  # [H, BT, 1]  — Moments-normalised (WRONG for critic)
    torch_lp_raw_np    = fixture["torch_out_lp_raw"]    # [H, BT]  — correct PyTorch reference
    torch_lp_normed_np = fixture["torch_out_lp_normed"] # [H, BT]  — wrong (for comparison)

    from src.algorithms.dreamer_srl.loss import TwoHotEncoding

    qv_logits = jnp.asarray(qv_logits_np)
    lambda_values = jnp.asarray(lambda_values_np)
    normed_lambda = jnp.asarray(normed_lambda_np)

    qv = TwoHotEncoding(qv_logits, dims=1)

    # Log_prob with raw lambda (what sheeprl does — this should match)
    lp_raw_jax = qv.log_prob(jax.lax.stop_gradient(lambda_values))  # [H, BT]
    diff_raw = float(np.max(np.abs(np.asarray(lp_raw_jax) - torch_lp_raw_np)))

    # Log_prob with normed lambda (what WRONG impl would do — this should NOT match)
    lp_normed_jax = qv.log_prob(jax.lax.stop_gradient(normed_lambda))  # [H, BT]
    diff_normed = float(np.max(np.abs(np.asarray(lp_normed_jax) - torch_lp_raw_np)))

    # --- Primary assertion: raw lambda must match (within D-006 threshold)
    assert diff_raw < THRESHOLD_TWOHOT_LP, (
        f"test_critic_target_lambda FAILED: log_prob(raw_lambda) does not match sheeprl.\n"
        f"  max_abs_diff={diff_raw:.3e} >= threshold={THRESHOLD_TWOHOT_LP:.1e}\n"
        f"  Sheeprl: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L314\n"
        f"  JAX: src/algorithms/dreamer_srl/loss.py:TwoHotEncoding.log_prob\n"
        f"  GOTCHA: critic must use UN-normalised lambda_values (raw), not Moments-normed."
    )

    # --- Distinguishability assertion: normed must NOT match (the two are >> 1e-4 apart)
    assert diff_normed > 1e-4, (
        f"test_critic_target_lambda FAILED: log_prob(normed_lambda) matches the PyTorch reference "
        f"for log_prob(raw_lambda) — this means raw and normed lambdas are too similar, "
        f"so the test cannot distinguish them (diff_normed={diff_normed:.4e}).\n"
        f"  Regenerate fixtures with a larger scale difference between raw and normed lambdas."
    )

    print(f"test_critic_target_lambda PASSED")
    print(f"  log_prob(raw_lambda)   max_abs_diff = {diff_raw:.3e} (< {THRESHOLD_TWOHOT_LP:.1e}) — MATCHES sheeprl")
    print(f"  log_prob(normed_lambda) max_abs_diff = {diff_normed:.3e} (>> 1e-4) — does NOT match (correct!)")
    print(f"  Conclusion: critic correctly uses UN-normalised lambda_values (Hafner §3.3)")


