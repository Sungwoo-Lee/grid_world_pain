def test_train_module_does_not_import_from_src_models():
    """train.py must NOT import from src.models.dreamer_v3_* (Lever B isolation rule).

    v2 Risks §13 / NNX_CONVENTIONS.md:
        dreamer-srl module does NOT import from src/models/ at any level.
        This prevents silently inheriting the legacy model's architecture
        decisions (e.g., different NNX conventions, different layer sizing).

    The grep check is the CI-level enforcement; this test provides the same
    check at pytest time.
    """
    import subprocess
    # Match only lines that are actual import statements (start with "import" or "from"),
    # not docstring text that mentions the isolation rule. The ^(import|from) pattern
    # anchors to the start of the line (after whitespace stripping) to avoid matching
    # comments or docstrings that reference src.models for documentation purposes.
    result = subprocess.run(
        ["grep", "-n", "-E", r"^\s*(import|from)\s+src\.models\.dreamer_v3",
         "src/algorithms/dreamer_srl/train.py"],
        capture_output=True,
        text=True,
        cwd=_REPO_ROOT,
    )
    assert result.returncode != 0, (
        f"train.py has actual import statement from src.models.dreamer_v3_* (Lever B violation!):\n"
        f"{result.stdout}"
    )


