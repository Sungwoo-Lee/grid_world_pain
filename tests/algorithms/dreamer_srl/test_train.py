def test_discount_weighting():
    """Discount = stop_gradient(cumprod(continues * gamma, axis=0) / gamma).

    Verifies §S6 discount cumprod weighting:
      1. discount[0] == 1.0 (when continues[0] = 1, §S5 true-continue splice).
      2. Full discount tensor matches PyTorch reference.
      3. discount[:-1].squeeze(-1) has shape [H, BT] (correct slice for loss weighting).

    Sheeprl source:
      dreamer_v3.py:L259-L260 (inside `with torch.no_grad():`)
        discount = torch.cumprod(continues * cfg.algo.gamma, dim=0) / cfg.algo.gamma
    """
    fixture = np.load(os.path.join(FIXTURE_DIR, "discount_weighting_input.npz"))

    continues_np    = fixture["continues"]                 # [H+1, BT, 1]
    gamma           = float(fixture["gamma"])
    torch_disc_full = fixture["torch_out_discount_full"]   # [H+1, BT, 1]
    torch_disc_sliced = fixture["torch_out_discount_sliced"]  # [H, BT]
    expected_disc_0 = float(fixture["expected_discount_0"])   # 1.0

    continues_jax = jnp.asarray(continues_np)
    discount_jax = compute_discount(continues_jax, gamma)  # [H+1, BT, 1]

    # --- Check full discount array against PyTorch reference
    disc_full_np = np.asarray(discount_jax)
    diff_full = float(np.max(np.abs(disc_full_np - torch_disc_full)))
    assert diff_full < THRESHOLD_DEFAULT, (
        f"test_discount_weighting FAILED on full discount tensor: "
        f"max_abs_diff={diff_full:.3e} >= threshold={THRESHOLD_DEFAULT:.1e}\n"
        f"  Sheeprl: vendor/sheeprl/sheeprl/algos/dreamer_v3/dreamer_v3.py:L259-L260\n"
        f"  JAX: src/algorithms/dreamer_srl/train.py:compute_discount\n"
        f"  GOTCHA: cumprod must divide by gamma (not multiply); discount[0] = continues[0] = 1.0"
    )

    # --- Check [0]=1 invariant: discount[0] should be continues[0] = 1.0
    disc_0_mean = float(jnp.mean(discount_jax[0]))
    assert abs(disc_0_mean - expected_disc_0) < 1e-5, (
        f"test_discount_weighting FAILED: discount[0].mean()={disc_0_mean:.6f} "
        f"expected ≈ {expected_disc_0:.1f}\n"
        f"  §S6 GOTCHA: discount[0] must be continues[0] (= 1.0 for no-termination at step 0). "
        f"Ensure the formula is cumprod(...) / gamma, NOT cumprod(...) * gamma or plain cumprod."
    )

    # --- Check sliced form: discount[:-1].squeeze(-1) shape = [H, BT]
    disc_sliced_jax = discount_jax[:-1].squeeze(-1)  # [H, BT]
    assert disc_sliced_jax.shape == torch_disc_sliced.shape, (
        f"test_discount_weighting FAILED: discount[:-1].squeeze(-1) shape mismatch: "
        f"jax={disc_sliced_jax.shape} torch={torch_disc_sliced.shape}"
    )
    disc_sliced_np = np.asarray(disc_sliced_jax)
    diff_sliced = float(np.max(np.abs(disc_sliced_np - torch_disc_sliced)))
    assert diff_sliced < THRESHOLD_DEFAULT, (
        f"test_discount_weighting FAILED on sliced discount: "
        f"max_abs_diff={diff_sliced:.3e} >= threshold={THRESHOLD_DEFAULT:.1e}"
    )

    # --- Verify stop_gradient semantics: discount must not have gradient
    # (This is a structural check — the computation should be wrapped in stop_gradient)
    # We can verify by checking that the function applies lax.stop_gradient
    # by inspecting the output (stop_gradient output is just the value, no jvp tracers)
    # In JAX, stop_gradient is semantically guaranteed by lax.stop_gradient in the code.
    # We verify it indirectly: grad through discount should be zero
    def _dummy_loss(c):
        d = compute_discount(c, gamma)
        return jnp.sum(d)

    grad = jax.grad(_dummy_loss)(continues_jax)
    max_grad = float(jnp.max(jnp.abs(grad)))
    assert max_grad < 1e-10, (
        f"test_discount_weighting FAILED: gradient flows through discount "
        f"(max_grad={max_grad:.3e}). "
        f"compute_discount must wrap the output in jax.lax.stop_gradient — "
        f"JAX equivalent of sheeprl's `with torch.no_grad():`."
    )

    print(f"test_discount_weighting PASSED")
    print(f"  full discount max_abs_diff    = {diff_full:.3e} (< {THRESHOLD_DEFAULT:.1e})")
    print(f"  discount[0].mean()            = {disc_0_mean:.6f} ≈ 1.0 ([0]=1 invariant)")
    print(f"  sliced discount max_abs_diff  = {diff_sliced:.3e} (< {THRESHOLD_DEFAULT:.1e})")
    print(f"  stop_gradient verified: max_grad = {max_grad:.2e} < 1e-10")


